'''Export NEC-81 far-field radiation patterns to NSMA WG16.99.050 (.adf).'''

from dataclasses import dataclass, field
from datetime import date
import math
from pathlib import Path


@dataclass
class AdfSession:
    '''Hold far-field pattern samples and antenna metadata for NSMA export.'''

    outputPath: Path | None = None
    comment: str = 'Generated by NEC-81 Python'
    modelNumber: str = 'NEC81-MODEL'
    vswr: float = 0.0
    dimensions_m: tuple[float, float, float] = (0.0, 0.0, 0.0)
    samples: list[dict] = field(default_factory=list)


adfSession = AdfSession()


def configureAdfExport(outputPath=None, comment=''):
    '''Reset and configure NSMA .adf export for one solver run.'''

    global adfSession
    isValidPath = isinstance(outputPath, (str, Path)) and bool(str(outputPath).strip())
    path = Path(outputPath) if outputPath else None
    adfSession = AdfSession(
        outputPath=path,
        comment=comment.strip() or 'Generated by NEC-81 Python',
    )


def setAdfMetadata(comment='', modelNumber='', vswr=None, dimensions_m=None):
    '''Update optional antenna metadata collected during geometry/solve.'''

    if comment:
        adfSession.comment = comment.strip()
    if modelNumber:
        adfSession.modelNumber = modelNumber.strip()
    if vswr is not None:
        adfSession.vswr = float(vswr)
    if dimensions_m is not None:
        adfSession.dimensions_m = tuple(float(v) for v in dimensions_m)


def recordAdfSample(
    freq_MHz,
    theta_deg,
    phi_deg,
    gtot_dBi,
    gvert_dBi,
    ghoriz_dBi,
    phase_deg=0.0,
):
    '''Record one far-field angle sample when NSMA .adf export is enabled.'''

    if adfSession.outputPath is None:
        return
    adfSession.samples.append({
        'freq_MHz': float(freq_MHz),
        'theta_deg': float(theta_deg),
        'phi_deg': float(phi_deg),
        'gtot_dBi': float(gtot_dBi),
        'gvert_dBi': float(gvert_dBi),
        'ghoriz_dBi': float(ghoriz_dBi),
        'phase_deg': float(phase_deg),
    })


def wrapSignedAngle(angle_deg):
    '''Wrap an angle into [-180.0, 180.0).'''

    wrapped = (float(angle_deg) + 180.0) % 360.0 - 180.0
    return 180.0 if math.isclose(wrapped, -180.0) else wrapped


def halfPowerBeamwidth(angles_deg, relGain_dB):
    '''Estimate -3 dB beamwidth around the peak sample in a sorted cut.'''

    if len(angles_deg) < 3:
        return 0.0
    peakIdx = max(range(len(relGain_dB)), key=lambda i: relGain_dB[i])
    leftAngle = angles_deg[0]
    for idx in range(peakIdx, 0, -1):
        if relGain_dB[idx] >= -3.0 and relGain_dB[idx - 1] < -3.0:
            span = relGain_dB[idx] - relGain_dB[idx - 1]
            frac = (-3.0 - relGain_dB[idx - 1]) / max(span, 1e-9)
            leftAngle = angles_deg[idx - 1] + frac * (
                angles_deg[idx] - angles_deg[idx - 1]
            )
            break
    rightAngle = angles_deg[-1]
    for idx in range(peakIdx, len(relGain_dB) - 1):
        if relGain_dB[idx] >= -3.0 and relGain_dB[idx + 1] < -3.0:
            span = relGain_dB[idx] - relGain_dB[idx + 1]
            frac = (-3.0 - relGain_dB[idx + 1]) / max(span, 1e-9)
            rightAngle = angles_deg[idx + 1] - frac * (
                angles_deg[idx + 1] - angles_deg[idx]
            )
            break
    return round(max(0.0, rightAngle - leftAngle), 1)


def extractFrequencyCuts(freqSamples):
    '''Build normalized AZ and EL cuts plus metrics for one frequency.'''

    peakSample = max(freqSamples, key=lambda s: s['gtot_dBi'])
    peakGain_dBi = peakSample['gtot_dBi']
    peakTheta = peakSample['theta_deg']
    peakPhi = peakSample['phi_deg']
    isVert = peakSample['gvert_dBi'] >= peakSample['ghoriz_dBi']
    polari = 'V/V' if isVert else 'H/H'
    gainKey = 'gvert_dBi' if isVert else 'ghoriz_dBi'

    # Azimuth cut at peak elevation (theta = peakTheta), wrapped to [-180, 180].
    azRows = {}
    for item in freqSamples:
        if math.isclose(item['theta_deg'], peakTheta, abs_tol=1e-4):
            az = round(wrapSignedAngle(item['phi_deg']), 4)
            azRows[az] = (
                az,
                item[gainKey] - peakGain_dBi,
                item['phase_deg'],
            )
    azCut = [azRows[k] for k in sorted(azRows)]

    # Elevation cut along peak azimuth plane (phi = peakPhi and peakPhi + 180).
    oppPhi = (peakPhi + 180.0) % 360.0
    elRows = {}
    for item in freqSamples:
        phiMod = item['phi_deg'] % 360.0
        if math.isclose(phiMod, peakPhi % 360.0, abs_tol=1e-4):
            el = round(90.0 - item['theta_deg'], 4)
            elRows[el] = (
                el,
                item[gainKey] - peakGain_dBi,
                item['phase_deg'],
            )
        elif math.isclose(phiMod, oppPhi, abs_tol=1e-4):
            el = round(wrapSignedAngle(90.0 + item['theta_deg']), 4)
            elRows[el] = (
                el,
                item[gainKey] - peakGain_dBi,
                item['phase_deg'],
            )
    elCut = [elRows[k] for k in sorted(elRows)]

    azWidth = halfPowerBeamwidth(
        [r[0] for r in azCut], [r[1] for r in azCut]
    )
    elWidth = halfPowerBeamwidth(
        [r[0] for r in elCut], [r[1] for r in elCut]
    )
    backGain = min(
        (r[1] for r in azCut if abs(abs(r[0]) - 180.0) <= 15.0),
        default=0.0,
    )
    frontToBack = round(abs(backGain), 1)
    elTilt = round(-(90.0 - peakTheta), 1)

    return {
        'peakGain_dBi': peakGain_dBi,
        'polari': polari,
        'azCut': azCut,
        'elCut': elCut,
        'azWidth': azWidth,
        'elWidth': elWidth,
        'frontToBack': frontToBack,
        'elTilt': elTilt,
    }


def buildRolodexSlices(freqSamples, gainKey, peakGain_dBi):
    '''Build full 3D rolodex elevation slices indexed by azimuth angle.'''

    phiSet = sorted({round(s['phi_deg'] % 360.0, 4) for s in freqSamples})
    if len(phiSet) < 3:
        return []

    slices = []
    visited = set()
    for basePhi in phiSet:
        if basePhi in visited:
            continue
        oppPhi = round((basePhi + 180.0) % 360.0, 4)
        visited.add(basePhi)
        hasOpp = any(math.isclose(p, oppPhi, abs_tol=1e-4) for p in phiSet)
        if hasOpp:
            visited.add(oppPhi)

        elRows = {}
        for item in freqSamples:
            phiMod = round(item['phi_deg'] % 360.0, 4)
            if math.isclose(phiMod, basePhi, abs_tol=1e-4):
                el = round(90.0 - item['theta_deg'], 4)
                elRows[el] = (
                    el,
                    item[gainKey] - peakGain_dBi,
                    item['phase_deg'],
                )
            elif hasOpp and math.isclose(phiMod, oppPhi, abs_tol=1e-4):
                el = round(wrapSignedAngle(90.0 + item['theta_deg']), 4)
                elRows[el] = (
                    el,
                    item[gainKey] - peakGain_dBi,
                    item['phase_deg'],
                )
        if len(elRows) >= 2:
            points = [elRows[k] for k in sorted(elRows)]
            slices.append((f'{basePhi:.2f}', points))
    return slices


def writeAdfFile(rolodex3d=True):
    '''Write collected far-field patterns to the configured NSMA .adf file.'''

    if adfSession.outputPath is None or not adfSession.samples:
        return None

    freqGroups = {}
    for sample in adfSession.samples:
        freqKey = round(sample['freq_MHz'], 6)
        freqGroups.setdefault(freqKey, []).append(sample)

    freqs = sorted(freqGroups)
    firstAnalysis = extractFrequencyCuts(freqGroups[freqs[0]])
    midFreq = freqs[len(freqs) // 2]
    midAnalysis = extractFrequencyCuts(freqGroups[midFreq])
    todayStr = date.today().strftime('%Y%m%d')
    dx, dy, dz = adfSession.dimensions_m

    lines = [
        'REVNUM:,NSMA WG16.99.050',
        'REVDAT:,19990520',
        f'COMNT1:,{adfSession.comment[:70]}',
        'ANTMAN:,NEC-81 Python',
        f'MODNUM:,{adfSession.modelNumber}',
        f'DESCR1:,NEC-81 far-field pattern ({len(freqs)} freq)',
        f'DTDATA:,{todayStr}',
        f'LOWFRQ:,{freqs[0]:.4f}',
        f'HGHFRQ:,{freqs[-1]:.4f}',
        'GUNITS:,DBI/DBR',
        f'MDGAIN:,{midAnalysis["peakGain_dBi"]:.2f},0.0',
        f'AZWIDT:,{firstAnalysis["azWidth"]:.1f},0.0',
        f'ELWIDT:,{firstAnalysis["elWidth"]:.1f},0.0',
        'CONTYP:,nec81 feed',
        f'ATVSWR:,{adfSession.vswr:.2f}',
        f'FRTOBA:,{firstAnalysis["frontToBack"]:.1f}',
        f'ELTILT:,{firstAnalysis["elTilt"]:.1f},0.0',
        'MAXPOW:,1000.0',
        f'ANTLEN:,{max(dx, dy):.3f}',
        f'ANTWID:,{min(dx, dy):.3f}',
        f'ANTDEP:,{dz:.3f}',
        'ANTWGT:,0.0',
        'PATTYP:,calculated',
        f'NOFREQ:,{len(freqs)}',
    ]

    for freq in freqs:
        samples = freqGroups[freq]
        info = extractFrequencyCuts(samples)
        gainKey = 'gvert_dBi' if info['polari'] == 'V/V' else 'ghoriz_dBi'
        cuts = []
        if info['elCut']:
            cuts.append(('EL', info['elCut']))
        if info['azCut']:
            cuts.append(('AZ', info['azCut']))
        if rolodex3d:
            cuts.extend(
                buildRolodexSlices(samples, gainKey, info['peakGain_dBi'])
            )

        lines.append(f'PATFRE:,{freq:.4f}')
        lines.append(f'NUMCUT:,{len(cuts)}')
        for cutName, points in cuts:
            lines.append(f'PATCUT:,{cutName}')
            lines.append(f'POLARI:,{info["polari"]}')
            lines.append(f'NUPOIN:,{len(points)}')
            lines.append(f'FSTLST:,{points[0][0]:.2f},{points[-1][0]:.2f}')
            for angle, relGain, phase in points:
                lines.append(f'{angle:8.2f},{relGain:9.3f},{phase:8.2f}')

    lines.append('ENDFIL:,EOF')
    outPath = adfSession.outputPath
    outPath.parent.mkdir(parents=True, exist_ok=True)
    outPath.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    return outPath

